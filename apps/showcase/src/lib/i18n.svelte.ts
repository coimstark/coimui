export class ShowcaseI18nState {
  private instance: i18n;
  locale = $state("en");

  constructor() {
    this.instance = i18next.createInstance();
    void this.instance.init({
      lng: "en",
      fallbackLng: "en",
      resources,
      interpolation: { escapeValue: false },
    });
  }

  t = (key: string): string => {
    void this.locale;
    return this.instance.t(key);
  };

  hydrateFromStorage = (): "ltr" | "rtl" => {
    if (typeof window === "undefined") return "ltr";
    try {
      const saved = window.localStorage.getItem(SHOWCASE_LOCALE_KEY);
      if (saved) {
        const match = SHOWCASE_LOCALES.find((l) => l.code === saved);
        if (match) {
          this.locale = match.code;
          void this.instance.changeLanguage(match.code);
          return match.dir;
        }
      }
    } catch {
      // Ignore storage restrictions
    }
    return SHOWCASE_LOCALES.find((l) => l.code === this.locale)?.dir ?? "ltr";
  };

  setLocale = (code: string): "ltr" | "rtl" => {
    const valid = SHOWCASE_LOCALES.find((l) => l.code === code) ?? SHOWCASE_LOCALES[0];
    this.locale = valid.code;
    void this.instance.changeLanguage(valid.code);
    if (typeof window !== "undefined") {
      try {
        window.localStorage.setItem(SHOWCASE_LOCALE_KEY, valid.code);
      } catch {
        // Ignore storage restrictions
      }
    }
    return valid.dir;
  };
}

export const showcaseI18n = new ShowcaseI18nState();
